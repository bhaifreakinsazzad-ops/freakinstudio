/**
 * Generates a plain SQL INSERT script from supabase/seed/data/*.json, for
 * pasting into the Supabase dashboard SQL editor as an alternative to
 * scripts/seed-services.ts (which needs the service-role key). Temporary
 * helper for the initial live-project seed — not part of the documented
 * workflow in README.md.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const DATA_DIR = path.resolve(__dirname, "../supabase/seed/data");

function sqlString(v: string | null | undefined): string {
  if (v === null || v === undefined) return "null";
  return `'${v.replace(/'/g, "''")}'`;
}
function sqlNum(v: number): string {
  return String(v);
}

type Category = { id: string; name: string; name_bn: string | null; sort_order: number };
type Service = {
  id: string;
  category_id: string;
  title: string;
  title_bn: string | null;
  base_usd: number;
  base_bdt: number;
  days: number;
  revisions: number;
  pricing_status: string;
};
type AddOn = { id: string; label: string; unit_price_usd: number; unit_price_bdt: number };
type ServiceAddOn = { service_id: string; add_on_id: string };

function readJson<T>(file: string): T[] {
  return JSON.parse(readFileSync(path.join(DATA_DIR, file), "utf-8")) as T[];
}

const categories = readJson<Category>("service-categories.json");
const services = readJson<Service>("services.json");
const addOns = readJson<AddOn>("add-ons.json");
const serviceAddOns = readJson<ServiceAddOn>("service-add-ons.json");

const lines: string[] = [];

lines.push("-- Generated by scripts/generate-seed-sql.ts from supabase/seed/data/*.json");
lines.push("-- Seeds the real 60-service catalog extracted verbatim from the legacy prototype.");
lines.push("");

lines.push("insert into public.service_categories (id, name, name_bn, sort_order) values");
lines.push(
  categories
    .map(
      (c) =>
        `  (${sqlString(c.id)}, ${sqlString(c.name)}, ${sqlString(c.name_bn)}, ${sqlNum(c.sort_order)})`,
    )
    .join(",\n") + "\non conflict (id) do update set name = excluded.name, name_bn = excluded.name_bn, sort_order = excluded.sort_order;",
);
lines.push("");

lines.push(
  "insert into public.services (id, category_id, title, title_bn, base_usd, base_bdt, days, revisions, pricing_status) values",
);
lines.push(
  services
    .map(
      (s) =>
        `  (${sqlString(s.id)}, ${sqlString(s.category_id)}, ${sqlString(s.title)}, ${sqlString(s.title_bn)}, ${sqlNum(s.base_usd)}, ${sqlNum(s.base_bdt)}, ${sqlNum(s.days)}, ${sqlNum(s.revisions)}, ${sqlString(s.pricing_status)})`,
    )
    .join(",\n") +
    "\non conflict (id) do update set category_id = excluded.category_id, title = excluded.title, title_bn = excluded.title_bn, base_usd = excluded.base_usd, base_bdt = excluded.base_bdt, days = excluded.days, revisions = excluded.revisions, pricing_status = excluded.pricing_status;",
);
lines.push("");

lines.push("insert into public.add_ons (id, label, unit_price_usd, unit_price_bdt) values");
lines.push(
  addOns
    .map(
      (a) =>
        `  (${sqlString(a.id)}::uuid, ${sqlString(a.label)}, ${sqlNum(a.unit_price_usd)}, ${sqlNum(a.unit_price_bdt)})`,
    )
    .join(",\n") +
    "\non conflict (id) do update set label = excluded.label, unit_price_usd = excluded.unit_price_usd, unit_price_bdt = excluded.unit_price_bdt;",
);
lines.push("");

lines.push("insert into public.service_add_ons (service_id, add_on_id) values");
lines.push(
  serviceAddOns
    .map((j) => `  (${sqlString(j.service_id)}, ${sqlString(j.add_on_id)}::uuid)`)
    .join(",\n") + "\non conflict (service_id, add_on_id) do nothing;",
);
lines.push("");

const out = lines.join("\n");
writeFileSync(path.resolve(__dirname, "../supabase/seed/0001_seed_catalog.generated.sql"), out);
console.log(`Wrote ${out.length} chars to supabase/seed/0001_seed_catalog.generated.sql`);
